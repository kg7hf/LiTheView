    private static void WriteCppStringPool(InvariantTextBuilder output, List<string> strings)
    {
        output.AppendLine($"inline constexpr std::array<std::string_view, {strings.Count}> kWidgetStrings{{{{");
        foreach (string value in strings)
        {
            output.AppendLine($"    {Quote(value)},");
        }
        output.AppendLine("}};");
        output.AppendLine();
    }

    private static void WriteCppProperties(
        InvariantTextBuilder output,
        WidgetPropertyDefinition[] properties,
        IReadOnlyDictionary<string, StringSlice> aliases,
        IReadOnlyDictionary<string, StringSlice> enumValues)
    {
        output.AppendLine(
            $"inline constexpr std::array<GeneratedPropertyDescriptor, {properties.Length}> kWidgetProperties{{{{");
        foreach (WidgetPropertyDefinition property in properties)
        {
            StringSlice alias = aliases[property.Id];
            StringSlice values = enumValues[property.Id];
            output.Append("    {")
                .Append(Quote(property.Id)).Append(", ")
                .Append(Quote(property.DisplayName)).Append(", ")
                .Append(Quote(ToName(property.Kind))).Append(", ")
                .Append(Quote(property.XmlName)).Append(", ")
                .Append(Slice(alias)).Append(", ")
                .Append(Quote(ToName(property.XmlTransform))).Append(", ")
                .Append(Quote(property.CppMember)).Append(", ")
                .Append(Quote(property.DefaultValue.GetRawText())).Append(", ")
                .Append(property.Minimum ?? 0L).Append(", ")
                .Append(property.Maximum ?? 0L).Append(", ")
                .Append(Bool(property.Minimum.HasValue)).Append(", ")
                .Append(Bool(property.Maximum.HasValue)).Append(", ")
                .Append(Quote(property.Units ?? string.Empty)).Append(", ")
                .Append(Bool(property.Required)).Append(", ")
                .Append(Slice(values)).Append(", ")
                .Append(Quote(property.Documentation)).AppendLine("},");
        }
        output.AppendLine("}};");
        output.AppendLine();
    }

