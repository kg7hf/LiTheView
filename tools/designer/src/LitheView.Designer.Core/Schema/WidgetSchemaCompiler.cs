    private static string GenerateDocumentation(WidgetCatalog catalog, string hash)
    {
        Dictionary<string, WidgetPropertyDefinition> properties = catalog.Properties.ToDictionary(
            property => property.Id,
            StringComparer.Ordinal);
        InvariantTextBuilder output = new();
        output.AppendLine("# Widget property reference");
        output.AppendLine();
        output.AppendLine("This file is generated from `schema/widgets.json`; do not edit it by hand.");
        output.AppendLine();
        output.AppendLine($"- Catalog: `{catalog.Id}`");
        output.AppendLine($"- Schema version: `{catalog.SchemaVersion}`");
        output.AppendLine($"- Compatibility version: `{catalog.CompatibilityVersion}`");
        output.AppendLine($"- Canonical SHA-256: `{hash}`");
        output.AppendLine();
        foreach (WidgetDefinition widget in catalog.Widgets.OrderBy(item => item.DisplayName, StringComparer.Ordinal))
        {
            output.AppendLine($"## {EscapeMarkdown(widget.DisplayName)}");
            output.AppendLine();
            output.AppendLine(widget.Help);
            output.AppendLine();
            output.AppendLine($"- ID: `{widget.Id}`");
            output.AppendLine($"- Runtime kind/type: `{widget.RuntimeKind}` / `{widget.CppType}`");
            output.AppendLine(
                $"- XML: `<{widget.Xml.Element}>` / `{widget.Xml.LegacyClass}`" +
                (widget.Xml.DiscriminatorPropertyId is null
                    ? string.Empty
                    : $"; selected by `{widget.Xml.DiscriminatorPropertyId}`"));
            output.AppendLine(
                $"- Default geometry: `{widget.DefaultGeometry.Width} by {widget.DefaultGeometry.Height}` pixels");
            output.AppendLine($"- Child policy: `{ToName(widget.ChildPolicy)}`");
            output.AppendLine();
            output.AppendLine("| Property | Kind | XML | Default | Range | Required | C++ member |");
            output.AppendLine("| --- | --- | --- | --- | --- | --- | --- |");
            foreach (string propertyId in widget.PropertyIds.Order(StringComparer.Ordinal))
            {
                WidgetPropertyDefinition property = properties[propertyId];
                string range = property.Minimum.HasValue || property.Maximum.HasValue
                    ? $"{property.Minimum?.ToString(CultureInfo.InvariantCulture) ?? "-"} to " +
                        $"{property.Maximum?.ToString(CultureInfo.InvariantCulture) ?? "+"}"
                    : "-";
                output.Append("| `").Append(property.Id).Append("` | `")
                    .Append(ToName(property.Kind)).Append("` | `")
                    .Append(property.XmlName).Append("` | `")
                    .Append(EscapeMarkdown(property.DefaultValue.GetRawText())).Append("` | ")
                    .Append(range).Append(" | ")
                    .Append(property.Required ? "yes" : "no").Append(" | `")
                    .Append(property.CppMember).AppendLine("` |");
            }
            output.AppendLine();
            output.AppendLine("### Property details");
            output.AppendLine();
            foreach (string propertyId in widget.PropertyIds.Order(StringComparer.Ordinal))
            {
                WidgetPropertyDefinition property = properties[propertyId];
                output.AppendLine($"- `{property.Id}`: {property.Documentation}");
            }
            output.AppendLine();
            WriteDocumentationList(output, "Actions", widget.Actions.Select(action =>
                $"`{action.Id}` ({action.Event}) - {action.DisplayName}; source `{action.RuntimeActionSource}`"));
            WriteDocumentationList(output, "Bindings", widget.Bindings.Select(binding =>
                $"`{binding.Id}` - {binding.DisplayName}; `{binding.PropertyId}`, {ToName(binding.Direction)}"));
            WriteDocumentationList(output, "States", widget.States.Select(state =>
                $"`{state.Id}` - {state.DisplayName}"));
            WriteDocumentationList(output, "Inputs", widget.InputCapabilities.Select(capability =>
                $"`{ToName(capability)}`"));
            WriteDocumentationList(output, "Resources", widget.Resources.Select(resource =>
                $"`{ToName(resource.Kind)}` through `{resource.PropertyId}`" +
                (resource.Required ? " (required)" : " (optional)")));
        }
        return Normalize(output);
    }

    private static void WriteDocumentationList(
        InvariantTextBuilder output,
        string heading,
        IEnumerable<string> values)
    {
        string[] materialized = [.. values.Order(StringComparer.Ordinal)];
        output.AppendLine($"### {heading}");
        output.AppendLine();
        if (materialized.Length == 0)
        {
            output.AppendLine("None.");
        }
        else
        {
            foreach (string value in materialized)
            {
                output.AppendLine($"- {value}");
            }
        }
        output.AppendLine();
    }

    private static StringSlice AddStrings(List<string> destination, IEnumerable<string> values)
    {
        string[] ordered = [.. values.Order(StringComparer.Ordinal)];
        StringSlice result = new(destination.Count, ordered.Length);
        destination.AddRange(ordered);
        return result;
    }

    private static string CSharpStrings(IEnumerable<string> values)
    {
        string[] ordered = [.. values.Order(StringComparer.Ordinal)];
        return ordered.Length == 0
            ? "ReadOnly<string>()"
            : $"ReadOnly({string.Join(", ", ordered.Select(Quote))})";
    }

    private static string CSharpActions(IEnumerable<WidgetActionDefinition> values)
    {
        string[] items = [.. values
            .OrderBy(item => item.Id, StringComparer.Ordinal)
            .Select(item =>
                $"new GeneratedActionDescriptor({Quote(item.Id)}, {Quote(item.DisplayName)}, " +
                $"{Quote(item.Event)}, {Quote(item.RuntimeActionSource)})")];
        return items.Length == 0
            ? "ReadOnly<GeneratedActionDescriptor>()"
            : $"ReadOnly({string.Join(", ", items)})";
    }

    private static string CSharpBindings(IEnumerable<WidgetBindingDefinition> values)
    {
        string[] items = [.. values
            .OrderBy(item => item.Id, StringComparer.Ordinal)
            .Select(item =>
                $"new GeneratedBindingDescriptor({Quote(item.Id)}, {Quote(item.DisplayName)}, " +
                $"{Quote(item.PropertyId)}, {Quote(ToName(item.Direction))})")];
        return items.Length == 0
            ? "ReadOnly<GeneratedBindingDescriptor>()"
            : $"ReadOnly({string.Join(", ", items)})";
    }

    private static string CSharpStates(IEnumerable<WidgetStateDefinition> values)
    {
        string[] items = [.. values
            .OrderBy(item => item.Id, StringComparer.Ordinal)
            .Select(item => $"new GeneratedStateDescriptor({Quote(item.Id)}, {Quote(item.DisplayName)})")];
        return items.Length == 0
            ? "ReadOnly<GeneratedStateDescriptor>()"
            : $"ReadOnly({string.Join(", ", items)})";
    }

    private static string CSharpResources(IEnumerable<WidgetResourceDependency> values)
    {
        string[] items = [.. values
            .OrderBy(item => item.PropertyId, StringComparer.Ordinal)
            .ThenBy(item => item.Kind)
            .Select(item =>
                $"new GeneratedResourceDescriptor({Quote(ToName(item.Kind))}, " +
                $"{Quote(item.PropertyId)}, {Bool(item.Required)})")];
        return items.Length == 0
            ? "ReadOnly<GeneratedResourceDescriptor>()"
            : $"ReadOnly({string.Join(", ", items)})";
    }

    private static string NullableNumber(long? value)
    {
        return value.HasValue
            ? value.Value.ToString(CultureInfo.InvariantCulture)
            : "null";
    }

    private static string Slice(StringSlice value)
    {
        return Slice(value.Offset, value.Count);
    }

    private static string Slice(int offset, int count)
    {
        return $"{{{offset}U, {count}U}}";
    }

    private static string Bool(bool value)
    {
        return value ? "true" : "false";
    }

    private static string ToName<TEnum>(TEnum value)
        where TEnum : struct, Enum
    {
        return StrictCamelCaseEnumConverter<TEnum>.ToJsonName(value);
    }

    private static string Quote(string value)
    {
        return JsonSerializer.Serialize(value, QuoteOptions);
    }

    private static string EscapeMarkdown(string value)
    {
        return value.Replace("|", "\\|", StringComparison.Ordinal);
    }

    private static byte[] Utf8(string value)
    {
        return new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(value);
    }

    private static string Normalize(InvariantTextBuilder output)
    {
        return output.ToString()
                   .Replace("\r\n", "\n", StringComparison.Ordinal)
                   .TrimEnd('\r', '\n') + "\n";
    }
