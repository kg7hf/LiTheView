    private static readonly JsonSerializerOptions QuoteOptions = new()
    {
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    };

    [InterpolatedStringHandler]
    private ref struct InvariantInterpolatedStringHandler(int literalLength, int formattedCount)
    {
        private DefaultInterpolatedStringHandler handler = new(
            literalLength,
            formattedCount,
            CultureInfo.InvariantCulture);

        public void AppendLiteral(string value)
        {
            handler.AppendLiteral(value);
        }

        public void AppendFormatted<T>(T value)
        {
            handler.AppendFormatted(value);
        }

        public readonly string GetFormattedText()
        {
            return handler.ToStringAndClear();
        }
    }

    private sealed class InvariantTextBuilder
    {
        private readonly StringBuilder builder = new();

        public InvariantTextBuilder Append(string value)
        {
            builder.Append(value);
            return this;
        }

        public InvariantTextBuilder Append(char value)
        {
            builder.Append(value);
            return this;
        }

        public InvariantTextBuilder Append(int value)
        {
            builder.Append(value.ToString(CultureInfo.InvariantCulture));
            return this;
        }

        public InvariantTextBuilder Append(long value)
        {
            builder.Append(value.ToString(CultureInfo.InvariantCulture));
            return this;
        }

        public InvariantTextBuilder AppendLine()
        {
            builder.AppendLine();
            return this;
        }

        public InvariantTextBuilder AppendLine(string value)
        {
            builder.AppendLine(value);
            return this;
        }

        public InvariantTextBuilder AppendLine(ref InvariantInterpolatedStringHandler value)
        {
            builder.AppendLine(value.GetFormattedText());
            return this;
        }

        public override string ToString()
        {
            return builder.ToString();
        }
    }

    private sealed record StringSlice(int Offset, int Count);

    private sealed record WidgetSlices(
        StringSlice ElementAliases,
        StringSlice LegacyClassAliases,
        StringSlice ParentIds,
        StringSlice PropertyIds,
        StringSlice InputCapabilities,
        int ActionOffset,
        int BindingOffset,
        int StateOffset,
        int ResourceOffset);

    public static WidgetSchemaCompilationResult Compile(WidgetCatalogLoadResult input)
    {
        ArgumentNullException.ThrowIfNull(input);

        if (!input.IsValid)
        {
            return new WidgetSchemaCompilationResult { Diagnostics = input.Diagnostics };
        }

        WidgetCatalog catalog = input.Catalog!;
        string hash = input.Sha256!;
        return new WidgetSchemaCompilationResult
        {
            CSharpUtf8 = Utf8(GenerateCSharp(catalog, hash)),
            CppUtf8 = Utf8(GenerateCpp(catalog, hash)),
            DocumentationUtf8 = Utf8(GenerateDocumentation(catalog, hash)),
            Diagnostics = input.Diagnostics
        };
    }

    private static string GenerateCSharp(WidgetCatalog catalog, string hash)
    {
        WidgetPropertyDefinition[] properties = [.. catalog.Properties.OrderBy(item => item.Id, StringComparer.Ordinal)];
        WidgetDefinition[] widgets = [.. catalog.Widgets.OrderBy(item => item.Id, StringComparer.Ordinal)];
        InvariantTextBuilder output = new();
        output.AppendLine("// SPDX-FileCopyrightText: 2026 Paul R. Decker");
        output.AppendLine("// SPDX-License-Identifier: GPL-3.0-only");
        output.AppendLine();
        output.AppendLine("// <auto-generated>");
        output.AppendLine("// Generated from schema/widgets.json. Do not edit by hand.");
        output.AppendLine("// </auto-generated>");
        output.AppendLine("#nullable enable");
        output.AppendLine();
        output.AppendLine("namespace LitheView.Designer.Schema.Generated;");
        output.AppendLine();
        output.AppendLine(
            "public sealed record GeneratedPropertyDescriptor(string Id, string DisplayName, " +
            "string Kind, string XmlName, IReadOnlyList<string> XmlAliases, string XmlTransform, " +
            "string CppMember, string DefaultJson, long? Minimum, long? Maximum, string? Units, " +
            "bool Required, IReadOnlyList<string> EnumValues, string Documentation);");
        output.AppendLine();
        output.AppendLine(
            "public sealed record GeneratedActionDescriptor(string Id, string DisplayName, " +
            "string Event, string RuntimeActionSource);");
        output.AppendLine();
        output.AppendLine(
            "public sealed record GeneratedBindingDescriptor(string Id, string DisplayName, " +
            "string PropertyId, string Direction);");
        output.AppendLine();
        output.AppendLine("public sealed record GeneratedStateDescriptor(string Id, string DisplayName);");
        output.AppendLine();
        output.AppendLine(
            "public sealed record GeneratedResourceDescriptor(string Kind, string PropertyId, bool Required);");
        output.AppendLine();
        output.AppendLine(
            "public sealed record GeneratedWidgetDescriptor(string Id, string DisplayName, " +
            "string RuntimeKind, string CppType, string PaletteGroup, string Help, int DefaultWidth, " +
            "int DefaultHeight, string XmlElement, IReadOnlyList<string> XmlElementAliases, " +
            "string LegacyClass, IReadOnlyList<string> LegacyClassAliases, string? DiscriminatorPropertyId, " +
            "bool RootAllowed, IReadOnlyList<string> AllowedParentIds, string ChildPolicy, " +
            "IReadOnlyList<string> PropertyIds, IReadOnlyList<GeneratedActionDescriptor> Actions, " +
            "IReadOnlyList<GeneratedBindingDescriptor> Bindings, IReadOnlyList<GeneratedStateDescriptor> States, " +
            "IReadOnlyList<string> InputCapabilities, IReadOnlyList<GeneratedResourceDescriptor> Resources);");
        output.AppendLine();
        output.AppendLine("public static class BuiltInWidgetCatalog");
        output.AppendLine("{");
        output.AppendLine($"    public const int SchemaVersion = {catalog.SchemaVersion};");
        output.AppendLine($"    public const int CompatibilityVersion = {catalog.CompatibilityVersion};");
        output.AppendLine($"    public const string CatalogId = {Quote(catalog.Id)};");
        output.AppendLine($"    public const string CatalogSha256 = {Quote(hash)};");
        output.AppendLine();
        output.AppendLine(
            "    public static IReadOnlyList<GeneratedPropertyDescriptor> Properties { get; } = " +
            "ReadOnly<GeneratedPropertyDescriptor>(");
        for (int index = 0; index < properties.Length; ++index)
        {
            WidgetPropertyDefinition property = properties[index];
            output.Append("        new(");
            output.Append(Quote(property.Id)).Append(", ");
            output.Append(Quote(property.DisplayName)).Append(", ");
            output.Append(Quote(ToName(property.Kind))).Append(", ");
            output.Append(Quote(property.XmlName)).Append(", ");
            output.Append(CSharpStrings(property.XmlAliases)).Append(", ");
            output.Append(Quote(ToName(property.XmlTransform))).Append(", ");
            output.Append(Quote(property.CppMember)).Append(", ");
            output.Append(Quote(property.DefaultValue.GetRawText())).Append(", ");
            output.Append(NullableNumber(property.Minimum)).Append(", ");
            output.Append(NullableNumber(property.Maximum)).Append(", ");
            output.Append(property.Units is null ? "null" : Quote(property.Units)).Append(", ");
            output.Append(property.Required ? "true" : "false").Append(", ");
            output.Append(CSharpStrings(property.EnumValues)).Append(", ");
            output.Append(Quote(property.Documentation)).Append(')');
            output.AppendLine(index + 1 == properties.Length ? ");" : ",");
        }
        output.AppendLine();
        output.AppendLine(
            "    public static IReadOnlyList<GeneratedWidgetDescriptor> Widgets { get; } = " +
            "ReadOnly<GeneratedWidgetDescriptor>(");
        for (int index = 0; index < widgets.Length; ++index)
        {
            WriteCSharpWidget(output, widgets[index], index + 1 == widgets.Length);
        }
        output.AppendLine();
        output.AppendLine("    private static IReadOnlyList<T> ReadOnly<T>(params T[] items)");
        output.AppendLine("    {");
        output.AppendLine("        return Array.AsReadOnly(items);");
        output.AppendLine("    }");
        output.AppendLine("}");
        return Normalize(output);
    }

    private static void WriteCSharpWidget(InvariantTextBuilder output, WidgetDefinition widget, bool last)
    {
        output.AppendLine("        new(");
        output.AppendLine($"            {Quote(widget.Id)},");
        output.AppendLine($"            {Quote(widget.DisplayName)},");
        output.AppendLine($"            {Quote(widget.RuntimeKind)},");
        output.AppendLine($"            {Quote(widget.CppType)},");
        output.AppendLine($"            {Quote(widget.PaletteGroup)},");
        output.AppendLine($"            {Quote(widget.Help)},");
        output.AppendLine($"            {widget.DefaultGeometry.Width},");
        output.AppendLine($"            {widget.DefaultGeometry.Height},");
        output.AppendLine($"            {Quote(widget.Xml.Element)},");
        output.AppendLine($"            {CSharpStrings(widget.Xml.ElementAliases)},");
        output.AppendLine($"            {Quote(widget.Xml.LegacyClass)},");
        output.AppendLine($"            {CSharpStrings(widget.Xml.LegacyClassAliases)},");
        output.AppendLine(
            $"            {(widget.Xml.DiscriminatorPropertyId is null ? "null" : Quote(widget.Xml.DiscriminatorPropertyId))},");
        output.AppendLine($"            {(widget.ParentRule.RootAllowed ? "true" : "false")},");
        output.AppendLine($"            {CSharpStrings(widget.ParentRule.AllowedParentIds)},");
        output.AppendLine($"            {Quote(ToName(widget.ChildPolicy))},");
        output.AppendLine($"            {CSharpStrings(widget.PropertyIds)},");
        output.AppendLine($"            {CSharpActions(widget.Actions)},");
        output.AppendLine($"            {CSharpBindings(widget.Bindings)},");
        output.AppendLine($"            {CSharpStates(widget.States)},");
        output.AppendLine($"            {CSharpStrings(widget.InputCapabilities.Select(ToName))},");
        output.AppendLine($"            {CSharpResources(widget.Resources)}){(last ? ");" : ",")}");
    }

    private static string GenerateCpp(WidgetCatalog catalog, string hash)
    {
        WidgetPropertyDefinition[] properties = [.. catalog.Properties.OrderBy(item => item.Id, StringComparer.Ordinal)];
        WidgetDefinition[] widgets = [.. catalog.Widgets.OrderBy(item => item.Id, StringComparer.Ordinal)];
        List<string> strings = [];
        Dictionary<string, StringSlice> propertyAliases = new(StringComparer.Ordinal);
        Dictionary<string, StringSlice> propertyEnums = new(StringComparer.Ordinal);
        foreach (WidgetPropertyDefinition property in properties)
        {
            propertyAliases[property.Id] = AddStrings(strings, property.XmlAliases);
            propertyEnums[property.Id] = AddStrings(strings, property.EnumValues);
        }

        List<WidgetActionDefinition> actions = [];
        List<WidgetBindingDefinition> bindings = [];
        List<WidgetStateDefinition> states = [];
        List<WidgetResourceDependency> resources = [];
        Dictionary<string, WidgetSlices> slices = new(StringComparer.Ordinal);
        foreach (WidgetDefinition widget in widgets)
        {
            int actionOffset = actions.Count;
            actions.AddRange(widget.Actions.OrderBy(item => item.Id, StringComparer.Ordinal));
            int bindingOffset = bindings.Count;
            bindings.AddRange(widget.Bindings.OrderBy(item => item.Id, StringComparer.Ordinal));
            int stateOffset = states.Count;
            states.AddRange(widget.States.OrderBy(item => item.Id, StringComparer.Ordinal));
            int resourceOffset = resources.Count;
            resources.AddRange(widget.Resources
                .OrderBy(item => item.PropertyId, StringComparer.Ordinal)
                .ThenBy(item => item.Kind));
            slices[widget.Id] = new WidgetSlices(
                AddStrings(strings, widget.Xml.ElementAliases),
                AddStrings(strings, widget.Xml.LegacyClassAliases),
                AddStrings(strings, widget.ParentRule.AllowedParentIds),
                AddStrings(strings, widget.PropertyIds),
                AddStrings(strings, widget.InputCapabilities.Select(ToName)),
                actionOffset,
                bindingOffset,
                stateOffset,
                resourceOffset);
        }

        InvariantTextBuilder output = new();
        output.AppendLine("// SPDX-FileCopyrightText: 2026 Paul R. Decker");
        output.AppendLine("// SPDX-License-Identifier: GPL-3.0-only");
        output.AppendLine();
        output.AppendLine("// <auto-generated>");
        output.AppendLine("// Generated from schema/widgets.json. Do not edit by hand.");
        output.AppendLine("// </auto-generated>");
        output.AppendLine("#pragma once");
        output.AppendLine();
        output.AppendLine("#include <array>");
        output.AppendLine("#include <cstddef>");
        output.AppendLine("#include <cstdint>");
        output.AppendLine("#include <string_view>");
        output.AppendLine();
        output.AppendLine("namespace lithe::designer");
        output.AppendLine("{");
        WriteCppStructures(output);
        output.AppendLine("// This immutable generated payload favors deterministic review and compact generation.");
        output.AppendLine("// NOLINTBEGIN(readability-magic-numbers)");
        output.AppendLine("// clang-format off");
        output.AppendLine($"inline constexpr std::int32_t kWidgetSchemaVersion{{{catalog.SchemaVersion}}};");
        output.AppendLine(
            $"inline constexpr std::int32_t kWidgetCompatibilityVersion{{{catalog.CompatibilityVersion}}};");
        output.AppendLine($"inline constexpr std::string_view kWidgetCatalogId{{{Quote(catalog.Id)}}};");
        output.AppendLine($"inline constexpr std::string_view kWidgetCatalogSha256{{{Quote(hash)}}};");
        output.AppendLine();
        WriteCppStringPool(output, strings);
        WriteCppProperties(output, properties, propertyAliases, propertyEnums);
        WriteCppActions(output, actions);
        WriteCppBindings(output, bindings);
        WriteCppStates(output, states);
        WriteCppResources(output, resources);
        WriteCppWidgets(output, widgets, slices);
        output.AppendLine("// clang-format on");
        output.AppendLine("// NOLINTEND(readability-magic-numbers)");
        output.AppendLine("} // namespace lithe::designer");
        return Normalize(output);
    }

