public static class FormCppCompiler
{
    private static readonly JsonSerializerOptions QuoteOptions = new()
    {
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    };

    // Direct enum properties name a scoped C++ enumeration whose enumerators are
    // the schema values. An enum without an entry fails closed instead of
    // emitting a string literal into a typed ViewSpec member.
    private static readonly Dictionary<string, string> DirectEnumCppTypes = new(StringComparer.Ordinal)
    {
        ["button-behavior"] = "ButtonBehavior"
    };

    [InterpolatedStringHandler]
    private ref struct InvariantInterpolatedStringHandler(int literalLength, int formattedCount)
    {
        private DefaultInterpolatedStringHandler handler = new(
            literalLength,
            formattedCount,
            CultureInfo.InvariantCulture);

        public void AppendLiteral(string value)
        {
            handler.AppendLiteral(value);
        }

        public void AppendFormatted<T>(T value)
        {
            handler.AppendFormatted(value);
        }

        public void AppendFormatted<T>(T value, string? format)
        {
            handler.AppendFormatted(value, format);
        }

        public readonly string GetFormattedText()
        {
            return handler.ToStringAndClear();
        }
    }

    private sealed class InvariantTextBuilder
    {
        private readonly StringBuilder builder = new();

        public void AppendLine()
        {
            builder.AppendLine();
        }

        public void AppendLine(string value)
        {
            builder.AppendLine(value);
        }

        public void AppendLine(ref InvariantInterpolatedStringHandler value)
        {
            builder.AppendLine(value.GetFormattedText());
        }

        public override string ToString()
        {
            return builder.ToString();
        }
    }

    public static FormCppCompilationResult Compile(FormDocument document, WidgetCatalog catalog)
    {
        FormResolutionResult resolution = FormDocumentResolver.Resolve(document, catalog);
        if (!resolution.IsValid || resolution.Document is null)
        {
            return new FormCppCompilationResult { Diagnostics = resolution.Diagnostics };
        }
        FormXmlWriteResult xml = FormXmlWriter.Write(resolution.Document);
        if (!xml.IsValid || xml.Sha256 is null)
        {
            return new FormCppCompilationResult { Diagnostics = xml.Diagnostics };
        }

        List<ProfileDiagnostic> diagnostics = [.. resolution.Diagnostics, .. xml.Diagnostics];
        try
        {
            return new FormCppCompilationResult
            {
                HeaderUtf8 = Utf8(GenerateHeader(
                    resolution.Document,
                    UsedRuntimeKinds(resolution.Document, catalog),
                    xml.Sha256,
                    Encoding.UTF8.GetString(xml.Utf8!))),
                IntegrationUtf8 = Utf8(GenerateIntegration(resolution.Document)),
                SourceXmlSha256 = xml.Sha256,
                Diagnostics = diagnostics
            };
        }
        catch (InvalidOperationException exception)
        {
            diagnostics.Add(new ProfileDiagnostic(
                "LVFG1001",
                ProfileDiagnosticSeverity.Error,
                "$",
                exception.Message));
            return new FormCppCompilationResult { Diagnostics = diagnostics };
        }
    }

    // The runtime kinds the form uses, in catalog order, which is also ViewKind order.
    private static string[] UsedRuntimeKinds(ResolvedFormDocument document, WidgetCatalog catalog)
    {
        HashSet<string> used = [.. document.Components.Select(component => component.Widget.RuntimeKind)];
        return [.. catalog.Widgets.Select(widget => widget.RuntimeKind).Where(used.Contains).Distinct()];
    }

    private static string GenerateHeader(
        ResolvedFormDocument document,
        string[] runtimeKinds,
        string xmlSha256,
        string canonicalXml)
    {
        bool typedEvents = runtimeKinds.Any(kind => ControlEventCatalog.For(kind).Any(item => item.Id != "clicked"));
        string form = document.CppSymbol;
        List<string> animationFrames = [];
        InvariantTextBuilder output = new();
        output.AppendLine("// <auto-generated>");
        output.AppendLine("// Generated by LitheView Designer. Edit only declared user-code regions.");
        output.AppendLine("// </auto-generated>");
        output.AppendLine("#pragma once");
        output.AppendLine();
        output.AppendLine("#include \"lithe/form_instance.hpp\"");
        output.AppendLine();
        if (typedEvents)
        {
            output.AppendLine("#if !__has_include(\"lithe/control_events.hpp\")");
            output.AppendLine("#error \"This form requires LiTheView typed control events. Update the application LiTheView dependency.\"");
            output.AppendLine("#else");
            output.AppendLine("#include \"lithe/control_events.hpp\"");
            output.AppendLine($"static_assert(lithe::kControlEventContractVersion >= {(runtimeKinds.Contains("dropDown") ? 3 : runtimeKinds.Contains("textField") ? 2 : 1)}U);");
            output.AppendLine("#endif");
            output.AppendLine();
        }
        output.AppendLine("#include <array>");
        output.AppendLine("#include <cstddef>");
        output.AppendLine("#include <cstdint>");
        output.AppendLine("#include <span>");
        output.AppendLine("#include <string_view>");
        output.AppendLine("#include <utility>");
        output.AppendLine();
        output.AppendLine("namespace lithe::generated");
        output.AppendLine("{");
        output.AppendLine();
        output.AppendLine($"struct {form} final");
        output.AppendLine("{");
        output.AppendLine("    // This immutable generated payload favors deterministic review and compact generation.");
        output.AppendLine("    // NOLINTBEGIN(readability-magic-numbers)");
        output.AppendLine("    // clang-format off");
        output.AppendLine($"    static constexpr std::int32_t kGeneratorContractVersion{{{(typedEvents ? 3 : 2)}}};");
        output.AppendLine($"    static constexpr std::int32_t kFormSchemaVersion{{{document.Source.SchemaVersion}}};");
        output.AppendLine($"    static constexpr std::string_view kDocumentId{{{Quote(document.Source.Id)}}};");
        output.AppendLine(
            $"    static constexpr std::string_view kSurfaceProfileId{{{Quote(document.Source.SurfaceProfileId ?? string.Empty)}}};");
        output.AppendLine($"    static constexpr std::string_view kSourceXmlSha256{{{Quote(xmlSha256)}}};");
        output.AppendLine("#if defined(LITHEVIEW_GENERATED_INCLUDE_SOURCE_XML)");
        output.AppendLine($"    static constexpr std::string_view kSourceXml{{{Quote(canonicalXml)}}};");
        output.AppendLine("#endif");
        output.AppendLine($"    static constexpr std::size_t kViewCount{{{document.Components.Length}U}};");
        output.AppendLine("    // The widget kinds this form uses. Layout builds only these, so a product links only");
        output.AppendLine("    // their widget code.");
        output.AppendLine(
            $"    using Widgets = WidgetSet<{string.Join(", ", runtimeKinds.Select(kind => $"ViewKind::{kind}"))}>;");
        output.AppendLine("    using Layout = StaticLayout<kViewCount, Widgets>;");
        output.AppendLine();
        WriteNamedContracts(output, document);
        WriteActions(output, document);
        WriteStateStyles(output, document);
        WriteViews(output, document, animationFrames);
        WriteAnimationFrames(output, animationFrames);
        output.AppendLine("    // clang-format on");
        output.AppendLine("    // NOLINTEND(readability-magic-numbers)");
        output.AppendLine("    static constexpr std::span<const ViewSpec> views() noexcept");
        output.AppendLine("    {");
        output.AppendLine("        return kViews;");
        output.AppendLine("    }");
        output.AppendLine();
        output.AppendLine("    static constexpr std::span<const std::string_view> animationFrames() noexcept");
        output.AppendLine("    {");
        output.AppendLine("        return kAnimationFrames;");
        output.AppendLine("    }");
        WriteInstance(output, document);
        output.AppendLine("};");
        output.AppendLine();
        output.AppendLine($"void dispatch{form}Action(ViewId action) noexcept;");
        output.AppendLine();
        output.AppendLine("} // namespace lithe::generated");
        return Normalize(output);
    }

    private static void WriteInstance(InvariantTextBuilder output, ResolvedFormDocument document)
    {
        output.AppendLine();
        output.AppendLine("    // Optional application-defined control replacements, selected at compile time.");
        foreach (ResolvedFormComponent component in document.Components)
        {
            output.AppendLine($"    template <typename Custom> using {component.CppSymbol}Type =");
            output.AppendLine($"        WidgetOverride<{component.Index}U, ViewKind::{component.Widget.RuntimeKind}, Custom>;");
        }
        output.AppendLine();
        output.AppendLine("    // Derive the handwritten form from Instance. Regeneration owns only this base.");
        output.AppendLine("    template <typename Overrides = WidgetOverrides<>>");
        output.AppendLine($"    class Instance : public FormInstance<{document.CppSymbol}, Overrides>");
        output.AppendLine("    {");
        output.AppendLine("    public:");
        foreach (ResolvedFormComponent component in document.Components)
        {
            output.AppendLine($"        auto* get{component.CppSymbol}() noexcept");
            output.AppendLine("        {");
            output.AppendLine($"            return this->template component<{component.Index}U, typename WidgetType<ViewKind::{component.Widget.RuntimeKind}>::Type>();");
            output.AppendLine("        }");
        }
        var events = document.Components.SelectMany(component =>
            ControlEventCatalog.For(component.Widget.RuntimeKind).Select(descriptor => (component, descriptor))).ToArray();
        output.AppendLine("    protected:");
        foreach (var (component, descriptor) in events)
        {
            string parameter = descriptor.ParameterType.Length == 0 ? "" :
                "[[maybe_unused]] " + descriptor.ParameterType + " event";
            output.AppendLine($"        virtual void on{component.CppSymbol}{descriptor.Suffix}({parameter}) noexcept");
            output.AppendLine("        {");
            output.AppendLine("        }");
        }
        output.AppendLine("    private:");
        // Keep numeric actions absorbed by a form even when it contains no buttons.
        output.AppendLine("        void onControlAction([[maybe_unused]] ViewController& controller, [[maybe_unused]] View& control) noexcept final");
        output.AppendLine("        {");
        foreach (var (component, descriptor) in events.Where(item => item.descriptor.Id == "clicked"))
        {
            output.AppendLine($"            if (&control == get{component.CppSymbol}())");
            output.AppendLine("            {");
            output.AppendLine($"                on{component.CppSymbol}{descriptor.Suffix}();");
            output.AppendLine("                return;");
            output.AppendLine("            }");
        }
        output.AppendLine("        }");
        foreach (var group in events.Where(item => item.descriptor.Id != "clicked").GroupBy(item => item.descriptor))
        {
            ControlEventDescriptor descriptor = group.Key;
            output.AppendLine($"        void {descriptor.DelegateMethod}([[maybe_unused]] ViewController& controller, View& control, {descriptor.ParameterType} event) noexcept final");
            output.AppendLine("        {");
            foreach (var (component, _) in group)
            {
                output.AppendLine($"            if (&control == get{component.CppSymbol}())");
                output.AppendLine("            {");
                output.AppendLine($"                on{component.CppSymbol}{descriptor.Suffix}(event);");
                output.AppendLine("                return;");
                output.AppendLine("            }");
            }
            output.AppendLine("        }");
        }
        output.AppendLine("    };");
    }

    private static void WriteNamedContracts(
        InvariantTextBuilder output,
        ResolvedFormDocument document)
    {
        FormBinding[] bindings = [.. document.Bindings.Values.OrderBy(item => item.Id, StringComparer.Ordinal)];
        output.AppendLine("    struct BindingContract");
        output.AppendLine("    {");
        output.AppendLine("        std::string_view name;");
        output.AppendLine("        std::uint16_t capacityBytes;");
        output.AppendLine("    };");
        output.AppendLine();
        output.AppendLine(
            $"    static constexpr std::array<BindingContract, {bindings.Length}U> kBindings{{{{");
        foreach (FormBinding binding in bindings)
        {
            int capacity = binding.CapacityBytes ?? 0;
            output.AppendLine($"        {{{Quote(binding.RuntimeName)}, {capacity}U}},");
        }
        output.AppendLine("    }};");
        output.AppendLine();

        FormResource[] resources = [.. document.Resources.Values.OrderBy(item => item.Id, StringComparer.Ordinal)];
        output.AppendLine(
            $"    static constexpr std::array<std::string_view, {resources.Length}U> kResourceNames{{{{");
        foreach (FormResource resource in resources)
        {
            output.AppendLine($"        {Quote(resource.RuntimeName)},");
        }
        output.AppendLine("    }};");
        output.AppendLine();
    }

    private static void WriteActions(InvariantTextBuilder output, ResolvedFormDocument document)
    {
        output.AppendLine("    // ViewId is the runtime action ABI even when one form uses only small values.");
        output.AppendLine("    // NOLINTNEXTLINE(performance-enum-size)");
        output.AppendLine("    enum class Action : ViewId");
        output.AppendLine("    {");
        FormAction[] actions = [.. document.Actions.Values.OrderBy(item => item.RuntimeId)];
        for (int index = 0; index < actions.Length; ++index)
        {
            FormAction action = actions[index];
            string suffix = index + 1 == actions.Length ? string.Empty : ",";
            output.AppendLine($"        {ToEnumConstant(action.Symbol)} = {action.RuntimeId}U{suffix}");
        }
        output.AppendLine("    };");
        output.AppendLine();
    }

    private static void WriteViews(
        InvariantTextBuilder output,
        ResolvedFormDocument document,
        List<string> animationFrames)
    {
        output.AppendLine("    static constexpr std::array<ViewSpec, kViewCount> kViews = []");
        output.AppendLine("    {");
        output.AppendLine("        std::array<ViewSpec, kViewCount> result{};");
        foreach (ResolvedFormComponent component in document.Components)
        {
            output.AppendLine("        {");
            output.AppendLine($"            ViewSpec& spec = result[{component.Index}U];");
            output.AppendLine($"            spec.kind = ViewKind::{component.Widget.RuntimeKind};");
            if (component.Properties.Any(IsStateStyleProperty))
            {
                output.AppendLine($"            spec.style.states = &kStateStyles[{component.Index}U];");
            }
            if (component.ParentIndex.HasValue)
            {
                output.AppendLine($"            spec.parent = {component.ParentIndex.Value}U;");
            }
            foreach (ResolvedFormProperty property in component.Properties)
            {
                if (!IsStateStyleProperty(property))
                {
                    WriteProperty(output, document, property, animationFrames);
                }
            }
            output.AppendLine("        }");
        }
        output.AppendLine("        return result;");
        output.AppendLine("    }();");
        output.AppendLine();
    }

    private static void WriteStateStyles(
        InvariantTextBuilder output,
        ResolvedFormDocument document)
    {
        output.AppendLine("    static constexpr std::array<WidgetStateStyle, kViewCount> kStateStyles = []");
        output.AppendLine("    {");
        output.AppendLine("        std::array<WidgetStateStyle, kViewCount> result{};");
        foreach (ResolvedFormComponent component in document.Components)
        {
            ResolvedFormProperty[] properties =
                [.. component.Properties.Where(IsStateStyleProperty)];
            if (properties.Length == 0)
            {
                continue;
            }
            // Build each sparse entry locally and copy it into place. GCC 13 constant
            // evaluation zero-fills the omitted members of an element written through a
            // reference after skipping untouched predecessors, which would turn every
            // omitted state color into explicit transparent black.
            output.AppendLine("        {");
            output.AppendLine("            WidgetStateStyle state{};");
            foreach (ResolvedFormProperty property in properties)
            {
                if (property.Value is not FormColorValue color)
                {
                    throw new InvalidOperationException(
                        $"State-style property '{property.Descriptor.Id}' is not a color.");
                }
                uint encoded = color.EncodedColor ??
                    document.ThemeColors[color.ThemeTokenId!].EncodedColor;
                output.AppendLine(
                    $"            {property.Descriptor.CppMember} = Color::fromLegacyValue(0x{encoded:x8}U);");
            }
            output.AppendLine($"            result[{component.Index}U] = state;");
            output.AppendLine("        }");
        }
        output.AppendLine("        return result;");
        output.AppendLine("    }();");
        output.AppendLine();
    }

    private static bool IsStateStyleProperty(ResolvedFormProperty property)
    {
        return property.Descriptor.CppMember.StartsWith("state.", StringComparison.Ordinal);
    }

    private static void WriteProperty(
        InvariantTextBuilder output,
        ResolvedFormDocument document,
        ResolvedFormProperty property,
        List<string> animationFrames)
    {
        string id = property.Descriptor.Id;
        switch (property.Value)
        {
            case FormRectangleValue rectangle:
                output.AppendLine(
                    $"            spec.frame = {{{rectangle.Value.X}, {rectangle.Value.Y}, {rectangle.Value.Width}, {rectangle.Value.Height}}};");
                break;
            case FormColorValue color:
                uint encoded = color.EncodedColor ?? document.ThemeColors[color.ThemeTokenId!].EncodedColor;
                output.AppendLine(
                    $"            {property.Descriptor.CppMember} = Color::fromLegacyValue(0x{encoded:x8}U);");
                break;
            case FormBooleanValue boolean:
                output.AppendLine(
                    $"            {property.Descriptor.CppMember} = {(boolean.Value ? "true" : "false")};");
                break;
            case FormSignedIntegerValue signed:
                output.AppendLine(
                    $"            {property.Descriptor.CppMember} = {signed.Value.ToString(CultureInfo.InvariantCulture)};");
                break;
            case FormUnsignedIntegerValue unsignedValue when id == "text-alignment-flags":
                WriteAlignment(output, unsignedValue.Value);
                break;
            case FormUnsignedIntegerValue unsignedValue:
                output.AppendLine(
                    $"            {property.Descriptor.CppMember} = {unsignedValue.Value}U;");
                break;
            case FormTextValue text when id == "focus-policy":
                if (text.Value != "auto")
                {
                    output.AppendLine($"            spec.focusable = {(text.Value == "true" ? "1" : "0")};");
                }
                break;
            case FormTextValue text when property.Descriptor.Kind == WidgetPropertyKind.Enum:
                if (!DirectEnumCppTypes.TryGetValue(id, out string? enumType))
                {
                    throw new InvalidOperationException($"Enum property '{id}' has no C++ enumeration.");
                }
                output.AppendLine($"            {property.Descriptor.CppMember} = {enumType}::{text.Value};");
                break;
            case FormTextValue text:
                output.AppendLine($"            {property.Descriptor.CppMember} = {Quote(text.Value)};");
                break;
            case FormReferenceValue reference:
                WriteReference(output, document, property.Descriptor, reference);
                break;
            case FormReferenceListValue references:
                int offset = animationFrames.Count;
                foreach (string referenceId in references.ReferenceIds)
                {
                    animationFrames.Add(document.Resources[referenceId].RuntimeName);
                }
                output.AppendLine($"            spec.animationFrameOffset = {offset}U;");
                output.AppendLine($"            spec.animationFrameCount = {references.ReferenceIds.Length}U;");
                break;
            default:
                throw new InvalidOperationException($"Property '{id}' cannot be emitted as C++.");
        }
    }

    private static void WriteReference(
        InvariantTextBuilder output,
        ResolvedFormDocument document,
        WidgetPropertyDefinition descriptor,
        FormReferenceValue reference)
    {
        switch (reference.ReferenceKind)
        {
            case FormReferenceKind.Action:
                output.AppendLine(
                    $"            {descriptor.CppMember} = {document.Actions[reference.ReferenceId].RuntimeId}U;");
                break;
            case FormReferenceKind.Binding:
                output.AppendLine(
                    $"            {descriptor.CppMember} = {Quote(document.Bindings[reference.ReferenceId].RuntimeName)};");
                break;
            case FormReferenceKind.Font:
            case FormReferenceKind.Bitmap:
                output.AppendLine(
                    $"            {descriptor.CppMember} = {Quote(document.Resources[reference.ReferenceId].RuntimeName)};");
                break;
            default:
                throw new InvalidOperationException($"Reference '{reference.ReferenceId}' cannot be emitted as C++.");
        }
    }

    private static void WriteAlignment(InvariantTextBuilder output, ulong flags)
    {
        string horizontal = (flags & 3U) switch
        {
            1U => "right",
            2U => "center",
            _ => "left"
        };
        string vertical = ((flags >> 2) & 3U) switch
        {
            1U => "bottom",
            3U => "center",
            _ => "top"
        };
        output.AppendLine(
            $"            spec.style.textAlign.horizontal = HorizontalAlign::{horizontal};");
        output.AppendLine($"            spec.style.textAlign.vertical = VerticalAlign::{vertical};");
    }

    private static void WriteAnimationFrames(InvariantTextBuilder output, List<string> frames)
    {
        output.AppendLine(
            $"    static constexpr std::array<std::string_view, {frames.Count}U> kAnimationFrames{{{{");
        foreach (string frame in frames)
        {
            output.AppendLine($"        {Quote(frame)},");
        }
        output.AppendLine("    }};");
        output.AppendLine();
    }

    private static string GenerateIntegration(ResolvedFormDocument document)
    {
        string form = document.CppSymbol;
        InvariantTextBuilder output = new();
        output.AppendLine("// Generated integration shell. Code inside user-code regions is preserved byte for byte.");
        output.AppendLine($"#include \"{ToFileStem(form)}.hpp\"");
        output.AppendLine();
        WriteStartRegion(output, $"{document.Source.Id}.includes");
        WriteEndRegion(output, $"{document.Source.Id}.includes");
        output.AppendLine();
        output.AppendLine("namespace lithe::generated");
        output.AppendLine("{");
        output.AppendLine();
        output.AppendLine($"void dispatch{form}Action(ViewId action) noexcept");
        output.AppendLine("{");
        output.AppendLine("    switch (action)");
        output.AppendLine("    {");
        foreach (FormAction action in document.Actions.Values.OrderBy(item => item.RuntimeId))
        {
            output.AppendLine(
                $"    case std::to_underlying({form}::Action::{ToEnumConstant(action.Symbol)}):");
            WriteStartRegion(output, $"{document.Source.Id}.action.{action.Id}", "        ");
            WriteEndRegion(output, $"{document.Source.Id}.action.{action.Id}", "        ");
            output.AppendLine("        break;");
        }
        output.AppendLine("    default:");
        output.AppendLine("        break;");
        output.AppendLine("    }");
        output.AppendLine("}");
        output.AppendLine();
        output.AppendLine("} // namespace lithe::generated");
        return Normalize(output);
    }

    private static void WriteStartRegion(InvariantTextBuilder output, string id, string indentation = "")
    {
        output.AppendLine($"{indentation}// LITHEVIEW USER CODE BEGIN {id}");
    }

    private static void WriteEndRegion(
        InvariantTextBuilder output,
        string id,
        string indentation = "")
    {
        output.AppendLine($"{indentation}// LITHEVIEW USER CODE END {id}");
    }

    private static string ToFileStem(string value)
    {
        StringBuilder output = new();
        foreach (char character in value)
        {
            if (char.IsAsciiLetterUpper(character) && output.Length > 0)
            {
                output.Append('_');
            }
            output.Append(char.ToLowerInvariant(character));
        }
        return output.ToString();
    }

    private static string ToEnumConstant(string value)
    {
        return char.ToLowerInvariant(value[0]) + value[1..];
    }

    private static string Quote(string value)
    {
        return JsonSerializer.Serialize(value, QuoteOptions);
    }

    private static byte[] Utf8(string value)
    {
        return new UTF8Encoding(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true)
            .GetBytes(value);
    }

    private static string Normalize(InvariantTextBuilder value)
    {
        return value.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }
}
