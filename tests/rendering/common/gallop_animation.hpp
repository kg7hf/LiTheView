#pragma once

#include "gallop_frames.hpp"
#include "gallop_indexed4_frames.hpp"
#include "lithe/layout.hpp"

#include <array>
#include <cstddef>
#include <cstdint>
#include <span>
#include <string_view>

namespace lithe::demo
{

enum class GallopResourceFormat : std::uint8_t
{
    alpha1,
    indexed4
};

inline constexpr std::uint32_t kGallopIntervalMs{90U};
inline constexpr std::array<std::string_view, assets::kGallopFrameCount> kGallopResourceNames{
    "gallop-f0",
    "gallop-f1",
    "gallop-f2",
    "gallop-f3",
    "gallop-f4",
    "gallop-f5",
    "gallop-f6",
    "gallop-f7",
};

// GallopResources is deliberately an example adapter, not a file loader or an
// asset policy hidden in LitheView::Core. It gives AnimatedImageView stable
// names and borrowed Bitmap descriptors for one checked-in sequence. The
// generated byte arrays and palette are immutable and must outlive this
// provider and every view that borrows its descriptors.
//
// The supplied 96-by-72 master favors visual fidelity so a developer can see
// what the animation path can deliver on a capable display. That choice costs
// 6,912 bytes for eight alpha1 frames or 27,648 bytes for eight indexed4
// frames. It is not a minimum requirement. If internal flash is tight, run
// tools/generate_gallop_frames.py with a smaller FRAME_WIDTH/FRAME_HEIGHT,
// such as 64-by-48 or 32-by-24; select alpha1 instead of indexed4; retain fewer
// frames; or put the immutable arrays in application-owned external memory.
// None of those choices requires a different widget or painter API.
//
// AnimatedImageView performs bounded integer nearest-neighbor scaling while
// drawing. A 96-by-72 frame can therefore appear at 576-by-432 with scale 6
// without storing a second expanded frame. Scaling trades painter work for ROM
// and preserves exact mask/palette values; pre-sized artwork trades ROM for
// less per-frame scaling work. Products should measure both choices on their
// target and retain the representation appropriate to their timing and memory
// budgets.
template <GallopResourceFormat Format> class GallopResources final : public ResourceProvider
{
public:
    explicit GallopResources(
        Color alpha1Tint = Color::rgb(0x2d6cdfU),
        std::span<const Color> indexedPalette = assets::kGallopPalette) noexcept
        : mAlpha1Tint(alpha1Tint), mIndexedPalette(indexedPalette)
    {
        configure();
    }

    const Bitmap* bitmap(std::string_view name) const noexcept override
    {
        for (std::size_t index = 0U; index < kGallopResourceNames.size(); ++index)
        {
            if (name == kGallopResourceNames[index])
            {
                return &mFrames[index];
            }
        }
        return nullptr;
    }

private:
    void configure() noexcept
    {
        if constexpr (Format == GallopResourceFormat::alpha1)
        {
            configureAlpha1();
        }
        else
        {
            configureIndexed4();
        }
    }

    void configureAlpha1() noexcept
    {
        const auto bytes = std::as_bytes(std::span{assets::kGallopBits});
        for (std::size_t index = 0U; index < mFrames.size(); ++index)
        {
            Bitmap& bitmap = mFrames[index];
            bitmap.data =
                bytes.subspan(index * assets::kGallopFrameBytes, assets::kGallopFrameBytes);
            bitmap.width = assets::kGallopFrameWidth;
            bitmap.height = assets::kGallopFrameHeight;
            bitmap.strideBytes = assets::kGallopFrameStrideBytes;
            bitmap.format = BitmapFormat::alpha1;
            bitmap.tint = mAlpha1Tint;
        }
    }

    void configureIndexed4() noexcept
    {
        const auto bytes = std::as_bytes(std::span{assets::kGallopIndexed4Bits});
        for (std::size_t index = 0U; index < mFrames.size(); ++index)
        {
            Bitmap& bitmap = mFrames[index];
            bitmap.data = bytes.subspan(index * assets::kGallopIndexed4FrameBytes,
                                        assets::kGallopIndexed4FrameBytes);
            bitmap.width = assets::kGallopFrameWidth;
            bitmap.height = assets::kGallopFrameHeight;
            bitmap.strideBytes = assets::kGallopIndexed4FrameStrideBytes;
            bitmap.format = BitmapFormat::indexed4;
            bitmap.palette = mIndexedPalette;
        }
    }

    Color mAlpha1Tint{};
    std::span<const Color> mIndexedPalette;
    std::array<Bitmap, assets::kGallopFrameCount> mFrames{};
};

} // namespace lithe::demo
